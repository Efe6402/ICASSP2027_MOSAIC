function cfg=rho_sweep_config(mode,overrides)
%RHO_SWEEP_CONFIG Configuration for the view-profile mixing experiment.
if nargin<1||isempty(mode), mode='full'; end
if nargin<2, overrides=struct(); end
root=fileparts(mfilename('fullpath')); rho0=5/102;
cfg=struct('root',root,'mode',char(mode), ...
    'default_truth_file',fullfile(root,'data','source_truth', ...
        'MOSAIC_PLANTED_BLOCK_TRUTH_ONLY.mat'), ...
    'selected_config_dir',fullfile(root,'selected_configurations','p_05000'), ...
    'data_dir',fullfile(root,'generated_data','rho_bank_p05000'), ...
    'results_root',fullfile(root,'results','rho_sweep_p05000'), ...
    'anchor_p',5000,'rho_reference',rho0, ...
    'rho_values',[rho0 .075 .125 .20 .35 .50], ...
    'selection_criteria',{{'f1_component'}},'top_k',3, ...
    'validation_count',10,'test_count',10,'seed_base',12082026, ...
    'overwrite_data',false,'verbose',true,'mosaic_restarts',6, ...
    'mosaic_max_iter',6000,'zw_max_iter',300,'zw_tol',1e-4, ...
    'zw_backend','exact_projection','save_fit_cache',true, ...
    'make_figures',true,'make_truth_figures',true);
if strcmpi(mode,'quick')
    cfg.anchor_p=100; cfg.rho_values=[rho0 .5]; cfg.top_k=1;
    cfg.validation_count=1; cfg.test_count=1;
    cfg.mosaic_restarts=1; cfg.mosaic_max_iter=60; cfg.zw_max_iter=30;
    cfg.data_dir=fullfile(root,'generated_data','quick_rho_bank');
end
f=fieldnames(overrides); for k=1:numel(f), cfg.(f{k})=overrides.(f{k}); end
assert(all(cfg.rho_values>=0&cfg.rho_values<=.5));
assert(any(abs(cfg.rho_values-cfg.rho_reference)<1e-12));
stamp=char(datetime('now','Format','yyyyMMdd_HHmmss'));
cfg.output_dir=fullfile(cfg.results_root,['run_',char(mode),'_',stamp]);
end
