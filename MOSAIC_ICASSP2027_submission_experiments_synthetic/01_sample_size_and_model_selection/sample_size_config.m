function cfg=sample_size_config(mode,overrides)
%SAMPLE_SIZE_CONFIG Configuration for model selection and p transfer.
if nargin<1||isempty(mode), mode='full'; end
if nargin<2, overrides=struct(); end
root=fileparts(mfilename('fullpath'));
cfg=struct('mode',char(mode),'root',root, ...
    'source_dataset',fullfile(root,'data','source_truth', ...
        'MOSAIC_PLANTED_BLOCK_TRUTH_ONLY.mat'), ...
    'data_dir',fullfile(root,'generated_data','sample_bank'), ...
    'results_root',fullfile(root,'results','model_selection'), ...
    'transfer_results_root',fullfile(root,'results','p5000_fixed_transfer'), ...
    'selected_config_dir',fullfile(root,'selected_configurations','p_05000'), ...
    'sample_counts',[20 100 300 1000 3000 5000 10000], ...
    'validation_count',10,'test_count',10,'screen_validation_count',3, ...
    'seed_base',12082026,'overwrite_data',false,'verbose',true, ...
    'shortlist_per_criterion',12,'top_k',3, ...
    'threshold_grid',unique([0,logspace(-6,0,121)]), ...
    'save_all_selected_fits',true,'make_figures',true, ...
    'mosaic_screen_restarts',2,'mosaic_refine_restarts',6, ...
    'mosaic_screen_max_iter',3000,'mosaic_refine_max_iter',6000, ...
    'zw_max_iter',300,'zw_tol',1e-4,'zw_backend','exact_projection', ...
    'cvx_spotcheck',false);
if strcmpi(mode,'quick')
    cfg.sample_counts=[20 100]; cfg.validation_count=2; cfg.test_count=2;
    cfg.screen_validation_count=1; cfg.shortlist_per_criterion=2;
    cfg.top_k=1; cfg.mosaic_screen_restarts=1; cfg.mosaic_refine_restarts=1;
    cfg.mosaic_screen_max_iter=30; cfg.mosaic_refine_max_iter=60;
    cfg.data_dir=fullfile(root,'generated_data','quick_sample_bank');
end
f=fieldnames(overrides); for k=1:numel(f), cfg.(f{k})=overrides.(f{k}); end
stamp=char(datetime('now','Format','yyyyMMdd_HHmmss'));
cfg.output_dir=fullfile(cfg.results_root,['run_',char(mode),'_',stamp]);
cfg.transfer_output_dir=fullfile(cfg.transfer_results_root,['run_',char(mode),'_',stamp]);
end
